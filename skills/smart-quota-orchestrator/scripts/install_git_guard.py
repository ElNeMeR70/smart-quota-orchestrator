#!/usr/bin/env python3
"""Git Pre-Commit Secret & Token-Tax Guard Installer (`sqo git-guard`).

Installs an ultra-fast (<40ms) `.git/hooks/pre-commit` shield in any Git repository that:
  1. Blocks commits containing hardcoded API keys, GitHub PATs, private keys, or DB URLs (`scrub_secrets.py`).
  2. Warns if a staged `AGENTS.md` / `CLAUDE.md` / `GEMINI.md` rule file exceeds 2,500 tokens/turn!
"""

from __future__ import annotations

import argparse
import os
import stat
import sys
from pathlib import Path


def _configure_utf8() -> None:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            try:
                stream.reconfigure(encoding="utf-8")
            except Exception:
                pass


HOOK_TEMPLATE = """#!/usr/bin/env python3
# Auto-generated by Smart Quota & Swarm Orchestrator (`sqo git-guard`)
import subprocess, sys
from pathlib import Path

SUITE_ROOT = Path(r"{suite_root}")
SCRUB = SUITE_ROOT / "skills" / "project-memory-vault" / "scripts" / "scrub_secrets.py"
TAX = SUITE_ROOT / "skills" / "prompt-tax-profiler" / "scripts" / "optimize_prompt_rules.py"

res = subprocess.run(["git", "diff", "--cached", "--name-only", "--diff-filter=ACM"], capture_output=True, text=True)
staged = [f.strip() for f in res.stdout.splitlines() if f.strip()]
if not staged or not SCRUB.is_file():
    sys.exit(0)

# 1. Scan staged files for hardcoded secrets
scan = subprocess.run([sys.executable, str(SCRUB), "--scan-workspace", "."], capture_output=True, text=True)
if "**Detected Leaks**: `0`" not in scan.stdout and '"leaks_found": 0' not in scan.stdout:
    sys.stderr.write("\\n[Smart Quota Git-Guard] COMMIT BLOCKED — Potential hardcoded secret detected!\\n")
    sys.stderr.write(scan.stdout + "\\n")
    sys.exit(1)

# 2. Check if always-on agent rule files were modified and warn on prompt-tax bloat
if any(Path(f).name in ("AGENTS.md", "CLAUDE.md", "GEMINI.md", ".cursorrules") for f in staged) and TAX.is_file():
    tax = subprocess.run([sys.executable, str(TAX), "--workspace", "."], capture_output=True, text=True)
    if "Grade C" in tax.stdout or "Grade D" in tax.stdout:
        sys.stderr.write("\\n[Smart Quota Git-Guard] WARNING — High Always-On Prompt Token Tax detected:\\n")
        sys.stderr.write(tax.stdout + "\\n")

sys.exit(0)
"""


def install_guard(workspace: Path, suite_root: Path) -> dict:
    git_dir = workspace / ".git"
    if not git_dir.is_dir():
        return {"installed": False, "error": f"No `.git` directory found in {workspace}"}

    hooks_dir = git_dir / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)
    hook_file = hooks_dir / "pre-commit"

    content = HOOK_TEMPLATE.format(suite_root=str(suite_root.resolve()))
    hook_file.write_text(content, encoding="utf-8", newline="\n")
    try:
        st = os.stat(hook_file)
        os.chmod(hook_file, st.st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)
    except OSError:
        pass

    return {
        "installed": True,
        "hook_path": str(hook_file).replace("\\", "/"),
        "suite_root": str(suite_root.resolve()).replace("\\", "/"),
    }


def main() -> int:
    _configure_utf8()
    parser = argparse.ArgumentParser(description="Install the Smart Quota pre-commit secret & prompt-tax Git hook.")
    parser.add_argument("--workspace", "-w", default=".", help="Git repository root.")
    args = parser.parse_args()

    suite_root = Path(__file__).resolve().parents[3]
    res = install_guard(Path(args.workspace).resolve(), suite_root)
    if not res["installed"]:
        print(f"[ERROR] {res['error']}", file=sys.stderr)
        return 1
    print(f"[OK] Installed Smart Quota Git Pre-Commit Guard at: {res['hook_path']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
